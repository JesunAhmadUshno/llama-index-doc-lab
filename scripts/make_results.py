"""Compute the metrics and verdicts from the raw run records.

Reads results/raw_runs.json (written by scripts/run_study.py),
enforces the pre-registered harness integrity gate, writes
results/metrics.json, results/verdicts.json and RESULTS.md. Every
number in RESULTS.md comes from the raw records; nothing is
hand-typed.
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from src.metrics import accuracy_metrics, median, percentile, spurious_rate  # noqa: E402

SIBLING_PROD_TOP1_HITS = 23  # mlops-evidence-lab, rag_samples.json
H1_MARGIN = 0.10
H2_MARGIN = 0.25
H3_RATIO_BAND = (0.5, 2.0)

ARMS = ("prod", "li")
ARM_NAMES = {"prod": "Production (rag-foundation Build hybrid)",
             "li": "LlamaIndex 0.14.25 (defaults, MiniLM-L6-v2)"}


def fmt(x, digits=4):
    if x is None:
        return "n/a"
    return f"{x:.{digits}f}"


def main():
    raw = json.loads((ROOT / "results" / "raw_runs.json").read_text())
    questions = raw["questions"]
    in_corpus = [q for q in questions if q["slice"] == "in_corpus"]
    adversarial = [q for q in questions if q["slice"] == "adversarial"]
    assert len(in_corpus) == 28 and len(adversarial) == 12, (
        f"frozen set shape broken: {len(in_corpus)} in-corpus, "
        f"{len(adversarial)} adversarial")

    metrics = {"builds": raw["builds"], "arms": {}}
    for arm in ARMS:
        acc = accuracy_metrics([
            {"ranked_docs": q[arm]["ranked_docs"],
             "expected_doc": q["expected_doc"]} for q in in_corpus
        ])
        floor = percentile(
            [q[arm]["top1_score"] for q in in_corpus], 10)
        spur = spurious_rate([
            {"ranked_docs": q[arm]["ranked_docs"],
             "top1_score": q[arm]["top1_score"]} for q in adversarial
        ], floor)
        lat = [q[arm]["latency_median_s"] for q in in_corpus]
        metrics["arms"][arm] = {
            "accuracy": acc,
            "floor": floor,
            "spurious": spur,
            "latency_median_s": median(lat),
            "latency_p95_s": percentile(lat, 95),
        }

    # Harness integrity gate (stop rule in PREREGISTRATION.md).
    gate_hits = metrics["arms"]["prod"]["accuracy"]["top1_hits"]
    if gate_hits != SIBLING_PROD_TOP1_HITS:
        print(
            f"INTEGRITY GATE FAILED: production top-1 hits {gate_hits} "
            f"of 28, sibling record is {SIBLING_PROD_TOP1_HITS}. "
            "Stop, fix the harness, rerun the whole study; "
            "DECISIONS.md records the cause. No results written.",
            file=sys.stderr)
        sys.exit(1)

    top5_diff = abs(metrics["arms"]["li"]["accuracy"]["top5"]
                    - metrics["arms"]["prod"]["accuracy"]["top5"])
    spur_diff = abs(metrics["arms"]["li"]["spurious"]["rate"]
                    - metrics["arms"]["prod"]["spurious"]["rate"])
    ratio = (raw["builds"]["li"]["build_per_doc_s"]
             / raw["builds"]["prod"]["build_per_doc_s"])
    verdicts = {
        "H1": "CONFIRMED" if top5_diff >= H1_MARGIN else "REFUTED",
        "H2": "CONFIRMED" if spur_diff >= H2_MARGIN else "REFUTED",
        "H3": "CONFIRMED" if H3_RATIO_BAND[0] <= ratio <= H3_RATIO_BAND[1]
              else "REFUTED",
        "detail": {
            "top5_diff": top5_diff,
            "spurious_diff": spur_diff,
            "build_ratio_li_over_prod": ratio,
        },
    }
    metrics["verdicts"] = verdicts

    (ROOT / "results" / "metrics.json").write_text(json.dumps(metrics, indent=1))
    (ROOT / "results" / "verdicts.json").write_text(json.dumps(verdicts, indent=1))

    env = raw["env"]
    lines = []
    lines.append("# RESULTS (generated by scripts/make_results.py "
                 "from results/raw_runs.json)")
    lines.append("")
    lines.append(
        f"Environment: Python {env['python']} on {env['platform']}, "
        f"machine {env['machine']}. Packages: "
        + ", ".join(f"{k} {v}" for k, v in env["packages"].items())
        + f". Embedding model {env['embed_model']} at revision "
        f"{env['embed_model_revision']}. Question set sha256 "
        f"{env['questions_sha256']}.")
    lines.append("")
    lines.append(
        f"Harness integrity gate: production top-1 reproduces the "
        f"sibling record ({gate_hits} of 28, mlops-evidence-lab "
        f"measured 23 of 28). Gate passed.")
    lines.append("")
    lines.append("## Headline metrics")
    lines.append("")
    lines.append("| Measure | Production | LlamaIndex |")
    lines.append("| --- | --- | --- |")
    p, l = metrics["arms"]["prod"], metrics["arms"]["li"]
    lines.append(f"| Top-1 hit rate (28) | {fmt(p['accuracy']['top1'])} "
                 f"({p['accuracy']['top1_hits']}/28) | "
                 f"{fmt(l['accuracy']['top1'])} "
                 f"({l['accuracy']['top1_hits']}/28) |")
    lines.append(f"| Top-5 hit rate (28) | {fmt(p['accuracy']['top5'])} "
                 f"({p['accuracy']['top5_hits']}/28) | "
                 f"{fmt(l['accuracy']['top5'])} "
                 f"({l['accuracy']['top5_hits']}/28) |")
    lines.append(f"| MRR (28) | {fmt(p['accuracy']['mrr'])} | "
                 f"{fmt(l['accuracy']['mrr'])} |")
    lines.append(f"| Similarity floor (own 10th percentile) | "
                 f"{fmt(p['floor'])} | {fmt(l['floor'])} |")
    lines.append(f"| Spurious retrieval rate (12) | "
                 f"{fmt(p['spurious']['rate'])} "
                 f"({p['spurious']['count']}/12) | "
                 f"{fmt(l['spurious']['rate'])} "
                 f"({l['spurious']['count']}/12) |")
    lines.append(f"| Query latency median (s) | "
                 f"{fmt(p['latency_median_s'])} | "
                 f"{fmt(l['latency_median_s'])} |")
    lines.append(f"| Query latency p95 (s) | {fmt(p['latency_p95_s'])} | "
                 f"{fmt(l['latency_p95_s'])} |")
    pb, lb = raw["builds"]["prod"], raw["builds"]["li"]
    lines.append(f"| Index build time, median of 3 (s) | "
                 f"{fmt(pb['build_median_s'], 3)} | "
                 f"{fmt(lb['build_median_s'], 3)} |")
    lines.append(f"| Build time per document (s) | "
                 f"{fmt(pb['build_per_doc_s'], 3)} | "
                 f"{fmt(lb['build_per_doc_s'], 3)} |")
    lines.append(f"| Index size on disk (bytes) | {pb['index_bytes']} | "
                 f"{lb['index_bytes']} |")
    lines.append(f"| Index units | {pb['chunk_count']} chunks | "
                 f"{lb['node_count']} nodes |")
    lines.append("")
    lines.append("## Verdicts")
    lines.append("")
    lines.append("| Hypothesis | Verdict | Evidence |")
    lines.append("| --- | --- | --- |")
    lines.append(f"| H1: top-5 hit rates differ by at least {H1_MARGIN} | "
                 f"{verdicts['H1']} | difference {fmt(top5_diff)} |")
    lines.append(f"| H2: spurious rates differ by at least {H2_MARGIN} | "
                 f"{verdicts['H2']} | difference {fmt(spur_diff)} |")
    lines.append(f"| H3: build time per doc within "
                 f"[{H3_RATIO_BAND[0]}, {H3_RATIO_BAND[1]}] | "
                 f"{verdicts['H3']} | LI/PROD ratio {fmt(ratio, 3)} |")
    lines.append("")

    for arm in ARMS:
        lines.append(f"## Per-question table, in-corpus: {ARM_NAMES[arm]}")
        lines.append("")
        lines.append("| Id | Expected | Rank of expected | Top-5 ranked "
                     "docs | Top-1 score | Latency median (s) |")
        lines.append("| --- | --- | --- | --- | --- | --- |")
        for q in in_corpus:
            ranked = q[arm]["ranked_docs"]
            rank = (ranked.index(q["expected_doc"]) + 1
                    if q["expected_doc"] in ranked else "absent")
            lines.append(
                f"| {q['id']} | {q['expected_doc']} | {rank} | "
                f"{', '.join(ranked[:5])} | {fmt(q[arm]['top1_score'])} | "
                f"{fmt(q[arm]['latency_median_s'])} |")
        lines.append("")
        lines.append(f"## Per-question table, adversarial: {ARM_NAMES[arm]}")
        lines.append("")
        lines.append("| Id | Category | Top-1 doc | Top-1 score | Floor | "
                     "Spurious | Latency median (s) |")
        lines.append("| --- | --- | --- | --- | --- | --- | --- |")
        floor = metrics["arms"][arm]["floor"]
        for q in adversarial:
            ranked = q[arm]["ranked_docs"]
            score = q[arm]["top1_score"]
            spurious = bool(ranked) and score is not None and score >= floor
            lines.append(
                f"| {q['id']} | {q['category']} | "
                f"{ranked[0] if ranked else 'none'} | {fmt(score)} | "
                f"{fmt(floor)} | {'yes' if spurious else 'no'} | "
                f"{fmt(q[arm]['latency_median_s'])} |")
        lines.append("")

    (ROOT / "RESULTS.md").write_text("\n".join(lines))
    print("verdicts:", verdicts)
    print(f"gate: production top-1 {gate_hits}/28 reproduced")


if __name__ == "__main__":
    main()
